"""Когда в мире появляется собака (спецификация 2.0, разделы 8 и 10).

- Настройка «Собака»: никогда / иногда (около 40 % миров) / часто - основа.
- Настроение человечка (acts/choice.Choice.mood, -1..1) её меняет: в хорошем собака приходит
  вероятнее и раньше, в грустном - реже. «Никогда» - всегда никогда.
- Собака может прийти и потом: раз в минуту - шанс по той же основе и настроению.
- Неручная через время уходит (тем скорее, чем меньше доверяет) и может вернуться та же - со
  своим доверием; ручная остаётся в своём мире.
"""
MODES = ("never", "sometimes", "often")
MODE_NAMES = {"never": "Никогда", "sometimes": "Иногда", "often": "Часто"}
WORLD = {"never": 0.0, "sometimes": 0.4, "often": 0.8}       # шанс, что собака есть в новом мире
LATER = {"never": 0.0, "sometimes": 0.025, "often": 0.07}    # шанс в минуту прийти потом
STAY = (4.0, 10.0)          # мин - сколько неручная побудет, пока не уйдёт (больше при доверии)
GONE = 25.0                 # м от него и за окном - ушла совсем


def mood_factor(mood):
    """Хорошее настроение (1) - почти вдвое чаще, грустное (-1) - в пять раз реже."""
    m = max(-1.0, min(1.0, float(mood)))
    return max(0.2, min(1.8, 1.0 + 0.8 * m))


def world_chance(mode, mood):
    return min(0.95, WORLD.get(mode, 0.0) * mood_factor(mood))


def minute_chance(mode, mood):
    return LATER.get(mode, 0.0) * mood_factor(mood)


def stay_minutes(trust, rng):
    lo, hi = STAY
    return float(rng.uniform(lo, hi)) * (1.0 + 2.0 * trust)
